import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { appendFile, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const hash = value => createHash('sha256').update(value).digest('hex')
export const coauthor = 'Co-authored-by: Tang Yixiao <115929632+tangyixiao@users.noreply.github.com>'

// Raw registry/source responses can change timestamps without changing an index.
// Keep the previous evidence until the index or maintained configuration changes.
export function createSnapshot(channels, previous) {
  const result = { format: 1, channels: {} }
  for (const [name, { config, index, summary }] of Object.entries(channels)) {
    assert.equal(hash(index), summary.indexSha256, `${name}: index/summary hash mismatch`)
    assert.equal(summary.market.allowPrerelease, name === 'preview', `${name}: wrong channel`)
    assert.deepEqual(summary.sources.map(source => source.id), ['curated', ...(config.upstreamSources ?? []).map(source => source.id)], `${name}: incomplete sources`)
    const configSha256 = hash(JSON.stringify(config))
    const old = previous?.channels?.[name]
    result.channels[name] = old?.configSha256 === configSha256 && old.indexSha256 === summary.indexSha256
      ? old : { configSha256, ...structuredClone(summary) }
  }
  assert.deepEqual(Object.keys(result.channels), ['stable', 'preview'], 'Both channels are required')
  result.contentSha256 = hash(JSON.stringify(Object.entries(result.channels).map(([name, channel]) => [name, channel.configSha256, channel.indexSha256])))
  return result
}

export function snapshotBody(snapshot) {
  return ['Refresh the validated market snapshot after successful Pages deployment.', '',
    '| Channel | Plugins | Versions | Conflicts | Index SHA-256 |', '| --- | ---: | ---: | ---: | --- |',
    ...Object.entries(snapshot.channels).map(([name, channel]) => `| ${name} | ${channel.summary.plugins} | ${channel.summary.versions} | ${channel.summary.conflicts} | \`${channel.indexSha256}\` |`), '',
    'Generated by github-actions[bot] from the four configured upstream markets and maintained exact pins.',
    'Tests and both channel builds passed before deployment. This PR records provenance and does not change plugin pins.',
    'Snapshot-only bot PRs merge automatically after the required build and repository checks pass.',
    'Preserve the bot author and the following co-author trailer in the final merge commit.', '', coauthor, ''].join('\n')
}

async function main() {
  const snapshotPath = path.join(root, 'market-snapshot.json')
  if (process.argv.includes('--restore')) {
    const snapshot = JSON.parse(Buffer.from(process.env.MARKET_SNAPSHOT, 'base64').toString('utf8'))
    assert.equal(snapshot.format, 1)
    assert.deepEqual(Object.keys(snapshot.channels), ['stable', 'preview'])
    await writeFile(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`)
    await writeFile(path.join(root, 'work/sync-pr-body.md'), snapshotBody(snapshot))
    return
  }
  const json = async file => JSON.parse(await readFile(path.join(root, file), 'utf8'))
  let previous
  try { previous = await json('market-snapshot.json') } catch (error) { if (error.code !== 'ENOENT') throw error }
  const channels = {}
  for (const [name, config, directory] of [['stable', 'market.json', 'dist'], ['preview', 'preview.market.json', 'dist/preview']]) {
    channels[name] = { config: await json(config), index: await readFile(path.join(root, directory, 'index.json')), summary: await json(`${directory}/summary.json`) }
  }
  const snapshot = createSnapshot(channels, previous)
  await writeFile(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`)
  if (process.env.GITHUB_OUTPUT) await appendFile(process.env.GITHUB_OUTPUT, `snapshot=${Buffer.from(JSON.stringify(snapshot)).toString('base64')}\n`)
  if (process.env.GITHUB_STEP_SUMMARY) await appendFile(process.env.GITHUB_STEP_SUMMARY, snapshotBody(snapshot))
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error); process.exitCode = 1 })
}
